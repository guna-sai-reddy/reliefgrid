"""
WebSocket connection manager for broadcasting real-time alerts to all
connected clients (dashboards, field apps).
"""
from fastapi import WebSocket
from typing import List


class ConnectionManager:
    def __init__(self):
        self.active: List[WebSocket] = []

    async def connect(self, ws: WebSocket):
        await ws.accept()
        self.active.append(ws)

    def disconnect(self, ws: WebSocket):
        if ws in self.active:
            self.active.remove(ws)

    async def broadcast(self, message: dict):
        dead: List[WebSocket] = []
        for ws in self.active:
            try:
                await ws.send_json(message)
            except Exception:
                dead.append(ws)
        for ws in dead:
            self.disconnect(ws)


# Global singleton — reused by endpoints and services
map_manager = ConnectionManager()
alert_manager = ConnectionManager()